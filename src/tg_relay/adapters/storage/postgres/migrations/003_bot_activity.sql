-- tg-relay: лимит ботов считает одновременно работающих ботов.
-- active_bots.last_seen обновляется при каждом сбросе учёта, а узел при
-- синхронизации читает ботов, активных за последние минуты, — нужен индекс.
CREATE INDEX IF NOT EXISTS active_bots_last_seen_idx ON active_bots(last_seen);

-- monthly_bot_limit теперь означает «сколько ботов может работать одновременно».
-- Имя колонки сохранено ради совместимости с существующими базами.
COMMENT ON COLUMN projects.monthly_bot_limit IS
    'Сколько ботов проекта может работать одновременно, 0 = без лимита';
